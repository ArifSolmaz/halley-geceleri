/* Gökyüzü verisini üretir: node tools/build_sky.js  (npm i --no-save astronomy-engine@2.1.19; d3-celestial verisi vendor/ altında — bkz. tools/README.md)
   Ardından: python3 tools/mw_tex.py  → data/milkyway.js */
// Builds browser data for the planetarium from: Horizons raw (Halley), astronomy-engine (Sun, Moon, planets),
// d3-celestial (Hipparcos stars, constellation lines/names, Milky Way outlines).
const fs=require('fs'), path=require('path'), A=require(process.env.ASTRONOMY_ENGINE||'astronomy-engine');
const ROOT=path.join(__dirname,'..');
const V=(process.env.D3C_DATA||path.join(ROOT,'vendor'))+'/', OUT=path.join(ROOT,'data')+'/';  // d3-celestial data/*.json dosyaları V altında
const LMT=6954.816, SITE=new A.Observer(41.0082,28.9784,30);
const T0=Date.UTC(1910,3,20,0,0,0)-LMT*1000;           // 1910-04-20 00:00 LMT
const T1=Date.UTC(1910,5,11,0,0,0)-LMT*1000;           // 1910-06-11 00:00 LMT
const r4=x=>Math.round(x*1e4)/1e4, r35=x=>Math.round(x*1e3)/1e3, r3=x=>Math.round(x*1e3)/1e3, r2=x=>Math.round(x*100)/100;
// ---------- Halley: tek kaynak tools/build_halley.js (aralığı kuşatan örnekler, PsAng çerçeve düzeltmesi) ----------
const RANGE_T1=T0+(Math.round((T1+3600e3-T0)/3600e3)+1-2)*3600e3;   // js/astro.js RANGE.max ile aynı
const {H,VAL}=require('./build_halley.js').build(T0,RANGE_T1);
fs.writeFileSync(path.join(ROOT,'tests/horizons_azel.json'),JSON.stringify(VAL));console.log('halley samples',H.ra.length,new Date(H.t0).toISOString());
// ---------- Sun, Moon, planets hourly (topocentric apparent, equator of date) ----------
const bodies=['Sun','Moon','Mercury','Venus','Mars','Jupiter','Saturn'];
const B={t0:T0,step:3600,names:bodies,ra:{},dec:{},mag:{},frac:{},dist:{}};
for(const b of bodies){B.ra[b]=[];B.dec[b]=[];B.mag[b]=[];B.frac[b]=[];B.dist[b]=[];}
for(let t=T0;t<=T1+3600e3;t+=3600e3){
  const d=new Date(t);
  for(const b of bodies){
    const eq=A.Equator(b,d,SITE,true,true);
    B.ra[b].push(r4(eq.ra*15));B.dec[b].push(r4(eq.dec));if(b==='Moon'||b==='Sun')B.dist[b].push(+eq.dist.toFixed(7));
    if(b!=='Sun'){const il=A.Illumination(b,d);B.mag[b].push(r2(il.mag));B.frac[b].push(r3(il.phase_fraction));}
  }
}
// ---------- stars: J2000 -> true equator of date (1910-05-15 12:00 UT) + annual aberration ----------
const tm=new Date(Date.UTC(1910,4,15,12));
const rot=A.Rotation_EQJ_EQD(A.MakeTime(tm));
const ev=A.BaryState(A.Body.Earth,A.MakeTime(tm)); // AU/day
const C=173.1446326846693; const beta=[ev.vx/C,ev.vy/C,ev.vz/C]; // EQJ frame
function toDate(raDeg,decDeg){
  const ra=raDeg*Math.PI/180,de=decDeg*Math.PI/180;
  let s=[Math.cos(de)*Math.cos(ra),Math.cos(de)*Math.sin(ra),Math.sin(de)];
  const dot=s[0]*beta[0]+s[1]*beta[1]+s[2]*beta[2];
  s=[s[0]+beta[0]-dot*s[0],s[1]+beta[1]-dot*s[1],s[2]+beta[2]-dot*s[2]];
  const n=Math.hypot(...s); s=s.map(x=>x/n);
  const v=A.RotateVector(rot,new A.Vector(s[0],s[1],s[2],A.MakeTime(tm)));
  let r=Math.atan2(v.y,v.x)*180/Math.PI; if(r<0)r+=360;
  return [r35(r),r35(Math.asin(v.z)*180/Math.PI)];
}
const st=JSON.parse(fs.readFileSync(V+'stars.6.json'));
const names=JSON.parse(fs.readFileSync(V+'starnames.json'));
const S=[]; const SN=[];
for(const f of st.features){
  let [lon,lat]=f.geometry.coordinates; let ra=lon<0?lon+360:lon;
  const [r,d]=toDate(ra,lat); const bv=parseFloat(f.properties.bv); 
  S.push(r,d,r2(f.properties.mag),isNaN(bv)?0.6:r2(bv));
  const n=names[f.id];
  if(n && n.name && f.properties.mag<2.6) SN.push({i:S.length/4-1,name:n.tr||n.name,latin:n.name});
}
console.log('stars',S.length/4,'named',SN.length);
// constellation lines
const cl=JSON.parse(fs.readFileSync(V+'constellations.lines.json'));
const CL={};
for(const f of cl.features){ CL[f.id]=f.geometry.coordinates.map(line=>line.map(([lo,la])=>toDate(lo<0?lo+360:lo,la))); }
const cn=JSON.parse(fs.readFileSync(V+'constellations.json'));
const CN=cn.features.map(f=>{const [lo,la]=f.geometry.coordinates;const [r,d]=toDate(lo<0?lo+360:lo,la);return {id:f.id,tr:f.properties.tr||f.properties.name,la:f.properties.name,rank:+f.properties.rank,ra:r,dec:d};});
// ecliptic & equator reference not needed here.
const sky={note:'Halley: NASA/JPL Horizons SAO/1910 topocentric apparent RA/Dec (true equator & equinox of date), 10 min; PsAng rotated from ICRF north to the true north of date, 10 min. Sun/Moon/planets: astronomy-engine 2.1.19, topocentric apparent of date, 1 h. Stars: Hipparcos via d3-celestial, precessed+nutated to 1910-05-15 with annual aberration.',
  lmtOffset:LMT, site:{lat:41.0082,lon:28.9784,elev:30}, halley:H, bodies:B, stars:S, starNames:SN, lines:CL, cnames:CN};
fs.writeFileSync(OUT+'sky.js','/* Generated by build/build_sky.js — see docs/05-bilim.md */\nwindow.SKY='+JSON.stringify(sky)+';\n');
console.log('sky.js bytes',fs.statSync(OUT+'sky.js').size);
// Milky Way polygons (precessed) for texture rendering
const mw=JSON.parse(fs.readFileSync(V+'mw.json'));
const MW=mw.features.map(f=>({id:f.id,polys:f.geometry.coordinates.map(poly=>poly.map(ring=>ring.map(([lo,la])=>toDate(lo<0?lo+360:lo,la))))}));
fs.writeFileSync(path.join(ROOT,'tools/mw_date.json'),JSON.stringify(MW));
